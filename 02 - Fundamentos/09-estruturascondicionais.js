//switch case: é uma estrutura de controle de fluxo que permite executar
let fruta = "Maçã";

switch (fruta) {
  case "Jaca":
    console.log("O valor da Maçã são R$2.00");
    break;
  case "Banana":
    console.log("O valor da Banana são R$2.00");
    break;
  case "Laranja":
    console.log("O valor Laranja são R$2.00");
    break;
}
