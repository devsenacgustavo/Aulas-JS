//operadores de comparação
//em javascript,os operadores de comparação são usados para comparar dois valores e retornar um valor booleano (true ou false)
//com base  na comparação. Aqui estão os principais opradoresde comparação:

//igualdade(==)
console.log("Igual (==)");
console.log(5 == "5"); //true, porque realiza coerção de tipo//true
console.log(5 == 5); //true
console.log(5 == 10); //False

// Estritamente igual (===)
console.log("Extritamente igual(===)");
console.log(5 == 5);
console.log(5 == 10);

//Desigualdade (!=)
console.log("Desigualdade (!=)");
console.log(5 != "5");
console.log(5 != 5);
console.log(5 != 10);

//estritamente desigual (!==)
console.log("Estritamente Desigual (!==)");
console.log(5 !== "5");
console.log(5 !== 5);
console.log(5 !== 10);

//Maior que(>)
console.log("Maior que (>)");
console.log(10 > 5);
console.log(5 > 10);
console.log(5 > 5);

//Menor que (<)
console.log("Menor que (<)");
console.log(10 < 5);
console.log(5 < 10);
console.log(5 < 5);

//Maior ou igual(>=)
console.log("Maior que (>=)");
console.log(10 >= 5);
console.log(5 >= 10);
console.log(5 >= 5);

//Menor que (<=)
console.log("Menor que (<=)");
console.log(10 <= 5);
console.log(5 <= 10);
console.log(5 <= 5);
